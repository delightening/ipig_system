-- 015: 標記哪些倉庫是「領用來源」
--
-- 背景（2026-09-09 使用者裁定）
-- ============================================================================
-- 建銷貨/領用單(SO)時，系統是「選儲位 → 反推倉庫」（migration 136 起逐行帶倉），
-- 所以「預設從哪裡領」這件事發生在儲位選單。使用者要的行為是
-- **依品項現有庫存自動帶**：選了品項之後，儲位預設帶「該品項目前有貨、
-- 且該倉庫是領用來源」的儲位——藥品自然帶準備室、耗材帶儲藏室，不必人工區分。
--
-- 為什麼 014 的兩個旗標不夠用
-- ============================================================================
-- `skip_routine_stocktake = true` 的有**儲藏室和廢棄物處理區兩個**，而廢棄區
-- 絕不能當領用來源——它根本不是庫存資產。用既有旗標反推會把廢棄區也算進去。
-- `exclude_from_alerts` 同理。那兩個旗標表達的是「要不要盤 / 要不要警報」，
-- 跟「能不能從這裡領貨」是不同的維度，硬套會在下一次需求變動時全部糾纏在一起。
--
-- 為什麼不加唯一性約束
-- ============================================================================
-- 直覺上「預設」該只有一個，但那是搭配「一律預設某個倉」的設計。
-- 實際裁定的是「依品項庫存自動帶」，於是**準備室與儲藏室都該是 true**：
-- 系統從「有貨的儲位」裡挑領用來源，藥品在準備室藥品櫃、耗材在儲藏室鐵櫃，
-- 兩者都是正當的領用點。加唯一約束會擋住這個正確用法。
--
-- 排除的是「有庫存數字但不該從那裡領」的地點：廢棄物處理區必然為 false；
-- 大倉庫是否為領用來源由使用者在 UI 決定（它是存貨大宗，實務上多半先調撥再領）。
--
-- 預設值刻意是 false
-- ============================================================================
-- 跑完**不改變任何現有行為**：沒有任何倉庫被標為領用來源時，自動帶邏輯
-- 找不到候選就退回「不預設」，與現在的行為一致。
--
-- ⚠️ 所以部署完這支之後還有一步：去倉庫管理頁把準備室與儲藏室勾起來。
-- 沒做這步，這支 migration 等於沒生效——與 014 是同一個模式，且理由相同：
-- 各環境（dev/staging/prod）的倉庫資料不同，用名稱或 code 去 UPDATE 會在
-- 別的環境命中錯的列，或一列都沒命中而靜默無事發生。

ALTER TABLE warehouses
    ADD COLUMN IF NOT EXISTS is_default_issue_source boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN warehouses.is_default_issue_source IS
    '此倉庫是否為領用來源：建 SO 時，若所選品項在這個倉庫有貨，儲位欄位會自動帶該倉的儲位。可同時有多個倉庫為 true（藥品在準備室、耗材在儲藏室都是正當領用點），系統再依品項實際庫存挑選；廢棄物處理區這類「有數字但不該從此領貨」的地點必須維持 false。';
