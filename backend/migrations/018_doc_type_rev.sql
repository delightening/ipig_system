-- 018: documents.doc_type 新增 REV（沖銷單）
--
-- 背景
-- ============================================================================
-- 沖銷單原本沿用原單的 doc_type（只靠 reverses_doc_id 辨識），所以入庫單的沖銷單在列表上
-- 的「類型」也是「採購入庫」、單號也是 GRN-…，看不出它是沖銷單。使用者 2026-10-28 裁定
-- 新增獨立的沖銷單類型 REV。
--
-- 為什麼拆成兩支 migration
-- ============================================================================
-- PostgreSQL 的限制：`ALTER TYPE ... ADD VALUE` 新增的列舉值，在**同一個交易**內不能被使用
-- （會報 unsafe use of new value）。sqlx 每支 migration 是一個交易，所以這支只加值，
-- 回填資料與一致性約束放在 019。
--
-- 回復（down，手動）
-- ============================================================================
-- PostgreSQL 無法移除列舉值。要回復必須先把 019 的回填反向（見 019 的回復說明），
-- 之後 REV 值留在型別裡無害（程式不再使用即可）。

ALTER TYPE doc_type ADD VALUE IF NOT EXISTS 'REV';
